#include <iostream>
#include <iomanip>
#include <cmath>
#include <vector>

using namespace std;

const int N = 3; // сколько у нас уравнений и сколько неизвестных

// -----------------------------------------------------------------------
// Функция для красивого вывода матрицы на экран
// -----------------------------------------------------------------------
void vivod_matr(vector<vector<double>>& M, int n) {
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++)
            cout << setw(10) << fixed << setprecision(4) << M[i][j] << " ";
        cout << endl;
    }
    cout << endl;
}

// -----------------------------------------------------------------------
// Функция для вывода найденных неизвестных x1, x2, x3
// -----------------------------------------------------------------------
void vivod_vectr(vector<double>& X, int n) {
    for (int i = 0; i < n; i++)
        cout << "x" << i + 1 << " = " << fixed << setprecision(6) << X[i] << endl;
    cout << endl;
}

// =========================================================================
// ЧТО ТАКОЕ СИСТЕМА УРАВНЕНИЙ Ax = b (объяснение "на пальцах")
//
// У нас есть 3 уравнения с тремя неизвестными x1, x2, x3:
//
//   4.59*x1 + 4.24*x2 + 3.82*x3 = 59.54
//   4.83*x1 + 4.36*x2 + 3.88*x3 = 62.33
//   4.06*x1 + 3.53*x2 + 3.01*x3 = 52.11
//
// Каждое такое уравнение - это уравнение ПЛОСКОСТИ в трёхмерном
// пространстве (как в геометрии: Ax+By+Cz=D - плоскость).
// Решить систему - значит найти точку (x1, x2, x3), через которую
// проходят ВСЕ ТРИ плоскости одновременно, то есть их общую точку
// пересечения.
//
// МЕТОД ГАУССА не пытается искать пересечение "на глаз" - вместо
// этого он ПОСТЕПЕННО УПРОЩАЕТ систему, используя три разрешённых
// действия (они называются "элементарные преобразования строк"):
//   1) поменять местами два уравнения;
//   2) умножить уравнение на любое число, не равное нулю;
//   3) прибавить к одному уравнению другое, умноженное на число.
//
// Важнейший факт (доказывается в курсе линейной алгебры): все три
// действия НЕ МЕНЯЮТ решение системы. Они лишь по-другому "упаковывают"
// те же самые условия. Пользуясь этим, можно последовательно исключать
// переменные (сначала x1 из 2-го и 3-го уравнений, потом x2 из
// 3-го уравнения), и получить "треугольную" систему вида:
//
//   a11*x1 + a12*x2 + a13*x3 = d1
//            a22*x2 + a23*x3 = d2
//                     a33*x3 = d3
//
// Из последней строки сразу находим x3, подставляем в предыдущую -
// находим x2, и так далее. Это называется "обратный ход".
// =========================================================================
void gauss(vector<vector<double>> A, vector<double> B, int n, vector<double>& X) {

    // ---------------------------------------------------------------
    // ШАГ 1. Склеиваем матрицу A и вектор b в одну общую таблицу.
    // Так удобнее: любое преобразование строки мы делаем сразу
    // и с коэффициентами, и с правой частью уравнения.
    // Получаем расширенную матрицу размером n x (n+1).
    // ---------------------------------------------------------------
    vector<vector<double>> M(n, vector<double>(n + 1));
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++)
            M[i][j] = A[i][j];
        M[i][n] = B[i]; // последний столбец - правая часть уравнения
    }

    // ---------------------------------------------------------------
    // ШАГ 2. ПРЯМОЙ ХОД - убираем переменные "снизу-слева",
    // превращая таблицу в треугольную.
    // k - номер переменной, которую исключаем на этом шаге (0, 1, 2)
    // ---------------------------------------------------------------
    for (int k = 0; k < n; k++) {

        // --- 2.1. Выбор главного элемента (partial pivoting) ---
        // Смотрим все строки НИЖЕ строки k в столбце k и находим ту,
        // где число по модулю самое большое. Меняем её местами со
        // строкой k. Зачем: если делить на маленькое число (или,
        // тем более, на ноль), результат "взрывается" от ошибок
        // округления. Вынося наверх самый "надёжный" (большой)
        // коэффициент, мы делаем вычисления точнее и безопаснее.
        int maxRow = k;
        double maxVal = fabs(M[k][k]);
        for (int i = k + 1; i < n; i++) {
            if (fabs(M[i][k]) > maxVal) {
                maxVal = fabs(M[i][k]);
                maxRow = i;
            }
        }
        if (maxRow != k)
            swap(M[k], M[maxRow]); // меняем местами две строки (два уравнения)

        // --- 2.2. Обнуляем переменную x_k во всех строках ниже строки k ---
        // Смысл: из строки i "вычитаем" строку k, умноженную на такое
        // число factor, чтобы в столбце k у строки i получился ровно ноль.
        // Это в точности третье элементарное преобразование из списка выше.
        for (int i = k + 1; i < n; i++) {
            double factor = M[i][k] / M[k][k];
            for (int j = k; j <= n; j++)
                M[i][j] -= factor * M[k][j];
        }
    }

    // ---------------------------------------------------------------
    // ШАГ 3. ОБРАТНЫЙ ХОД.
    // Теперь таблица треугольная. Последняя строка содержит только
    // одну неизвестную - находим её. Затем поднимаемся на строку выше:
    // там уже две неизвестные, но одна (найденная только что) известна,
    // поэтому находим вторую. И так далее, снизу вверх.
    // ---------------------------------------------------------------
    X.assign(n, 0.0);
    for (int i = n - 1; i >= 0; i--) {
        double sum = M[i][n]; // правая часть строки i
        for (int j = i + 1; j < n; j++)
            sum -= M[i][j] * X[j]; // отнимаем уже известные неизвестные
        X[i] = sum / M[i][i];
    }
}

// -----------------------------------------------------------------------
// Главная программа
// -----------------------------------------------------------------------
int main() {

    // Матрица коэффициентов A (ваши данные)
    vector<vector<double>> A = {
        {4.59, 4.24, 3.82},
        {4.83, 4.36, 3.88},
        {4.06, 3.53, 3.01}
    };

    // Вектор свободных членов b
    vector<double> B = {59.54, 62.33, 52.11};

    cout << "Iskhodnaya matritsa A:" << endl;
    vivod_matr(A, N);

    vector<double> X;
    gauss(A, B, N, X);

    cout << "Metod Gaussa. Reshenie sistemy:" << endl;
    vivod_vectr(X, N);

    return 0;
}
