#include <iostream>
#include <iomanip>
#include <cmath>
#include <vector>

using namespace std;

const int N = 3;

void vivod_matr(vector<vector<double>>& M, int n) {
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++)
            cout << setw(10) << fixed << setprecision(4) << M[i][j] << " ";
        cout << endl;
    }
    cout << endl;
}

void vivod_vectr(vector<double>& X, int n) {
    for (int i = 0; i < n; i++)
        cout << "x" << i + 1 << " = " << fixed << setprecision(6) << X[i] << endl;
    cout << endl;
}

// =========================================================================
// ЧТО ТАКОЕ МЕТОД ХОЛЕЦКОГО (объяснение "на пальцах" + высшая математика)
//
// Идея: любую симметричную положительно определённую матрицу C можно
// разложить в произведение
//
//        C = L * L^T
//
// где L - нижнетреугольная матрица (все числа выше главной диагонали -
// нули), а L^T - её "зеркальное отражение" относительно диагонали
// (то есть транспонированная матрица: L^T[i][j] = L[j][i]).
//
// Почему это требует именно "симметричности и положительной
// определённости"? Объясним простыми словами:
//   - Симметричная означает C[i][j] = C[j][i] - матрица одинаковая,
//     если её отразить по диагонали.
//   - Положительно определённая - это как условие a > 0 у параболы
//     y = a*x^2 в школьной алгебре, только для матриц: для любого
//     ненулевого набора чисел v выполняется v^T * C * v > 0.
//     На практике это условие гарантирует, что при построении L
//     под квадратным корнем никогда не появится отрицательное число
//     (иначе разложение было бы невозможно - нельзя извлечь
//     квадратный корень из отрицательного числа в вещественных числах).
//
// ПРОБЛЕМА: наша матрица A (см. main()) НЕ симметрична: посмотрите,
// A[0][1] = 4.24, а A[1][0] = 4.83 - это разные числа. Значит,
// напрямую метод Холецкого к A применить нельзя.
//
// РЕШЕНИЕ (стандартный приём линейной алгебры - "метод нормальных
// уравнений"). Умножим ОБЕ части уравнения A*x = b слева на
// транспонированную матрицу A^T:
//
//     A^T * (A * x) = A^T * b
//     (A^T * A) * x = A^T * b
//            C * x = y,      где   C = A^T*A,   y = A^T*b
//
// Почему C = A^T*A обязательно симметрична? Проверим по определению
// транспонирования произведения: C^T = (A^T*A)^T = A^T*(A^T)^T = A^T*A = C.
// Получили, что C^T = C - а это и есть определение симметричной матрицы.
// А если столбцы исходной матрицы A линейно независимы (не выражаются
// друг через друга - у нас так и есть, иначе система вообще не имела
// бы единственного решения), то C ещё и положительно определена.
// Значит, к C уже МОЖНО применять метод Холецкого.
//
// (Этот же приём "домножить на A^T" используется в статистике и
// машинном обучении при выводе метода наименьших квадратов.)
// =========================================================================
void holetsky(vector<vector<double>> A, vector<double> B, int n, vector<double>& X) {

    // ---------------------------------------------------------------
    // ШАГ 1. Строим симметричную матрицу C = A^T * A.
    // C[i][j] получаем, перемножая i-й и j-й СТОЛБЦЫ матрицы A
    // и складывая результаты (это и есть умножение матриц).
    // ---------------------------------------------------------------
    vector<vector<double>> C(n, vector<double>(n, 0.0));
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            double sum = 0.0;
            for (int t = 0; t < n; t++)
                sum += A[t][i] * A[t][j];
            C[i][j] = sum;
        }
    }

    // ---------------------------------------------------------------
    // ШАГ 2. Строим вектор y = A^T * b (правую часть новой системы).
    // ---------------------------------------------------------------
    vector<double> y(n, 0.0);
    for (int i = 0; i < n; i++) {
        double sum = 0.0;
        for (int j = 0; j < n; j++)
            sum += A[j][i] * B[j];
        y[i] = sum;
    }

    cout << "Matritsa normal'nykh uravneniy C = A^T*A:" << endl;
    vivod_matr(C, n);

    // ---------------------------------------------------------------
    // ШАГ 3. Разложение Холецкого: C = L * L^T.
    // Заполняем L строка за строкой, слева направо (только нижний
    // треугольник, включая диагональ - выше диагонали остаются нули).
    // ---------------------------------------------------------------
    vector<vector<double>> L(n, vector<double>(n, 0.0));
    for (int i = 0; i < n; i++) {
        for (int j = 0; j <= i; j++) {

            // "Уже учтённая" часть - сумма произведений элементов,
            // которые мы посчитали на предыдущих шагах.
            double sum = 0.0;
            for (int t = 0; t < j; t++)
                sum += L[i][t] * L[j][t];

            if (i != j) {
                // Элемент НЕ на главной диагонали
                L[i][j] = (C[i][j] - sum) / L[j][j];
            } else {
                // Элемент НА главной диагонали - тут и берём корень.
                // Если C положительно определена, под корнем всегда
                // будет число >= 0, поэтому корень существует.
                L[i][i] = sqrt(C[i][i] - sum);
            }
        }
    }

    // ---------------------------------------------------------------
    // ШАГ 4. ПРЯМОЙ ХОД: решаем L*z = y.
    // L - нижнетреугольная, значит первое уравнение содержит только
    // z[0], поэтому идём СВЕРХУ ВНИЗ (как обычная система "step by step").
    // ---------------------------------------------------------------
    vector<double> z(n, 0.0);
    z[0] = y[0] / L[0][0];
    for (int i = 1; i < n; i++) {
        double sum = y[i];
        for (int j = 0; j < i; j++)
            sum -= L[i][j] * z[j];
        z[i] = sum / L[i][i];
    }

    // ---------------------------------------------------------------
    // ШАГ 5. ОБРАТНЫЙ ХОД: решаем L^T*x = z.
    // L^T - верхнетреугольная, значит последнее уравнение содержит
    // только x[n-1] - идём СНИЗУ ВВЕРХ.
    // Важно: транспонировать L физически не нужно - помним, что
    // (L^T)[i][j] = L[j][i], и просто меняем местами индексы.
    // ---------------------------------------------------------------
    X.assign(n, 0.0);
    X[n - 1] = z[n - 1] / L[n - 1][n - 1];
    for (int i = n - 2; i >= 0; i--) {
        double sum = z[i];
        for (int j = i + 1; j < n; j++)
            sum -= L[j][i] * X[j];
        X[i] = sum / L[i][i];
    }
}

int main() {

    // Матрица коэффициентов A (ваши данные)
    vector<vector<double>> A = {
        {4.59, 4.24, 3.82},
        {4.83, 4.36, 3.88},
        {4.06, 3.53, 3.01}
    };

    // Вектор свободных членов b
    vector<double> B = {59.54, 62.33, 52.11};

    cout << "Iskhodnaya matritsa A:" << endl;
    vivod_matr(A, N);

    vector<double> X;
    holetsky(A, B, N, X);

    cout << "Metod Holetckogo. Reshenie sistemy:" << endl;
    vivod_vectr(X, N);

    return 0;
}
